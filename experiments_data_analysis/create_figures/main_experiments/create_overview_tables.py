import pandas as pd
from experiments_data_analysis.data_interface.column_names_merged_table import Col
from pathlib import Path


def create_overview_table(
        data_path: Path,
        output_path: Path,
        figures_dir: Path
):
    # Load CSV
    full_data_tables = pd.read_csv(data_path)

    keep_columns = [
        Col.MODEL, Col.REGULARIZATION, Col.DATA_DISTRIBUTION, Col.LOCAL_EPOCHS,
        Col.OVERFITTING_GAP_LOSS, Col.OVERFITTING_GAP_ACC, Col.METRICS_AUC
    ]

    overview_table = full_data_tables[keep_columns]

    # Map regularization from bool to German labels (Ohne / Mit)
    overview_table[Col.REGULARIZATION] = overview_table[Col.REGULARIZATION].map(
        {False: "Ohne", True: "Mit"}
    )

    # Rename columns to (mostly) German headers
    overview_table = overview_table.rename(columns={
        Col.MODEL: "Modell",
        Col.REGULARIZATION: "Reg.",
        Col.DATA_DISTRIBUTION: "Datenverteilung",
        Col.LOCAL_EPOCHS: "Epochen",
        Col.OVERFITTING_GAP_LOSS: "OGL",
        Col.OVERFITTING_GAP_ACC: "OGA",
        Col.METRICS_AUC: "AUC",
    })

    # Ensure categorical sorting
    overview_table["Modell"] = pd.Categorical(
        overview_table["Modell"], categories=["Shokri-CNN", "ResNet-18"], ordered=True
    )
    overview_table["Reg."] = pd.Categorical(
        overview_table["Reg."], categories=["Ohne", "Mit"], ordered=True
    )
    overview_table["Datenverteilung"] = pd.Categorical(
        overview_table["Datenverteilung"],
        categories=["IID", "semi-non-IID", "non-IID"],
        ordered=True
    )
    overview_table["Epochen"] = pd.Categorical(
        overview_table["Epochen"], categories=[1, 5, 10], ordered=True
    )

    # Sort in the desired grid order
    overview_table = overview_table.sort_values(
        ["Modell", "Reg.", "Datenverteilung", "Epochen"]
    )

    # Save CSV overview
    file_name_overview = output_path / "overview.csv"
    overview_table.to_csv(file_name_overview, index=False)

    # For LaTeX: use a MultiIndex to enable \multirow blocks
    latex_df = overview_table.set_index(
        ["Modell", "Reg.", "Datenverteilung", "Epochen"]
    )

    latex_table = latex_df.to_latex(
        longtable=True,
        multirow=True,
        multicolumn=False,
        index_names=False,
        column_format="llllSSS",   # siunitx S columns for numeric values
        float_format="%.2f",
        caption="Übersicht über alle Experimente.",
        label="tab:experiment_overview",
        escape=False,
    )

    # ---------- Custom header (German, with all column names) ----------
    correct_header = (
        "\\toprule\n"
        "Modell & Reg. & Datenverteilung & Epochen & OGL & OGA & AUC \\\\\n"
        "\\midrule\n"
        "\\endfirsthead\n"
        "\\caption[]{Übersicht über alle Experimente.} \\\\\n"
        "\\toprule\n"
        "Modell & Reg. & Datenverteilung & Epochen & OGL & OGA & AUC \\\\\n"
        "\\midrule\n"
        "\\endhead\n"
    )

    auto_head_start = "\\toprule"
    auto_head_end = "\\endhead"

    start_idx = latex_table.find(auto_head_start)
    end_idx = latex_table.find(auto_head_end) + len(auto_head_end)

    auto_header_block = latex_table[start_idx:end_idx]

    # Replace full autogenerated header with the custom header
    latex_table = latex_table.replace(auto_header_block, correct_header, 1)

    # ---------- Continuation text in German, with period ----------
    latex_table = latex_table.replace(
        "Continued on next page", "Fortsetzung auf der nächsten Seite."
    ).replace(
        "continued from previous page", "Fortsetzung von der vorherigen Seite."
    )

    # ---------- Explanatory note for abbreviations under the table ----------
    latex_table = latex_table.replace(
        "\\end{longtable}",
        "\\end{longtable}\n"
        "\\footnotesize{"
        "\\textbf{Reg.}: Regularisierung, "
        "\\textbf{OGL}: Overfitting Gap Loss, "
        "\\textbf{OGA}: Overfitting Gap Accuracy, "
        "\\textbf{AUC}: Area Under the Attack ROC Curve."
        "}\n"
    )

    file_name_text = figures_dir / "table_latex.tex"
    with open(file_name_text, "w") as f:
        f.write(latex_table)

    print("✅ Overview table created successfully (German, siunitx, annotated).")
